function append(fileName, additions) {
  const file = path.join(DATA, fileName);
  const existing = JSON.parse(fs.readFileSync(file, 'utf8'));
  const seen = new Set(existing.map(fingerprint));

  let nextId = existing.reduce((max, q) => Math.max(max, Number(q.id) || 0), 0) + 1;
  const fresh = [];
  let skipped = 0;
  for (const q of additions) {
    if (seen.has(fingerprint(q))) { skipped++; continue; }
    seen.add(fingerprint(q));
    fresh.push(Object.assign({ id: nextId++ }, q));
  }

  if (fresh.length) {
    fs.writeFileSync(file, JSON.stringify(existing.concat(fresh), null, 2) + '\n', 'utf8');
  }
  console.log(
    `${fileName.padEnd(24)} ${String(existing.length).padStart(4)} -> ${String(existing.length + fresh.length).padStart(4)}` +
    `  (+${fresh.length}${skipped ? `, ${skipped} already present` : ''})`
  );
  return fresh.length;
}

