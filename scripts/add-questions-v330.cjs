// Identity of a question for dedupe: its prompt (the snippet plus the English
// question), normalised. Catches a re-run and any accidental copy/paste repeat.
function fingerprint(q) {
  const prompt = [q.codeSnippet || '', q.question ? q.question.en : '', q.correctLanguage || '']
    .join('|');
  return prompt.replace(/\s+/g, ' ').trim().toLowerCase();
}

// Refuse to write anything unless every addition is well formed. A wrong answer
// in a quiz is worse than a missing question, so this runs before the first write.
function validate(bank, additions) {
  const problems = [];
  additions.forEach((q, i) => {
    const at = `${bank}[${i}]`;
    if (!q.difficulty || !['easy', 'medium', 'hard'].includes(q.difficulty)) {
      problems.push(`${at}: bad difficulty ${JSON.stringify(q.difficulty)}`);
    }
    if (!q.explanation || !q.explanation.en || !q.explanation.ar) {
      problems.push(`${at}: explanation needs both en and ar`);
    }
    if (q.correctLanguage) {
      if (!LANGUAGE_POOL.includes(q.correctLanguage)) {
        problems.push(`${at}: "${q.correctLanguage}" is not in the LANGUAGES pool`);
      }
      if (!q.codeSnippet || !q.codeSnippet.trim()) problems.push(`${at}: empty codeSnippet`);
      return;
    }
    if (!q.question || !q.question.en || !q.question.ar) {
      problems.push(`${at}: question needs both en and ar`);
    }
    if (Array.isArray(q.options)) {
      if (q.options.length < 4) problems.push(`${at}: needs at least 4 options`);
      if (new Set(q.options).size !== q.options.length) problems.push(`${at}: duplicate options`);
      if (!q.options.includes(q.answer)) problems.push(`${at}: answer is not one of the options`);
      return;
    }
    // Fill-in-the-blank.
    if (!q.codeSnippet || !q.codeSnippet.includes('____')) {
      problems.push(`${at}: fill-in snippet must contain ____`);
    }
    if (typeof q.answer !== 'string' || !q.answer.trim()) problems.push(`${at}: empty answer`);
    if (q.accept && !Array.isArray(q.accept)) problems.push(`${at}: accept must be an array`);
    // The grader lowercases and collapses whitespace, so accept entries that only
    // differ by case are dead weight and usually signal a copy/paste slip.
    const norm = (s) => String(s).trim().toLowerCase().replace(/\s+/g, ' ');
    if (Array.isArray(q.accept) && new Set(q.accept.map(norm)).size !== q.accept.length) {
      problems.push(`${at}: accept has entries that normalise to the same value`);
    }
  });
  return problems;
}

